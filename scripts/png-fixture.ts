/**
 * Test helper: the first 24 bytes of a PNG of the given size, which is all
 * `readPngSize` reads. Lets tests describe icons without committed image files.
 */
export function pngHeader(width: number, height = width): Uint8Array {
  const bytes = new Uint8Array(24)
  bytes.set([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a], 0)
  bytes.set([0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52], 8)
  const view = new DataView(bytes.buffer)
  view.setUint32(16, width)
  view.setUint32(20, height)
  return bytes
}
